# -*- coding: utf-8 -*-
"""生成「停止后台程序.bat」。

为什么用脚本生成而不是直接写 .bat：
1. 编码 —— cmd 按 GBK 解析批处理，UTF-8 文件里的中文会变成乱码并连带语法出错；
2. 引号 —— 经 shell 命令行拼接过一次的内容会被路径转换吃掉 `"/c:..."` 里的引号，
   生成出 `findstr /c:/` 这种既匹配不到、又可能误杀的表达。写成文件可彻底避免转义。

脚本行为：找出监听 gateway 端口（默认 8765）的进程并结束。
命令行进程（run.py --live）与桌面 GUI 都占这个端口，二者只能活一个。
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

BODY = '''@echo off
setlocal enabledelayedexpansion
cd /d "%~dp0"

rem ============================================================
rem  Stop whatever is listening on the bridge port (8765).
rem  Covers the command-line process (run.py --live) and the
rem  desktop GUI - only one of them can hold the port.
rem
rem  NOTE: do not edit this file in a UTF-8 editor and save it
rem  back - cmd reads .bat as GBK, Chinese text would garble.
rem  Regenerate with tools/gen_stop_bat.py if changes are needed.
rem ============================================================

set "PORT=8765"
set "FOUND="

for /f "tokens=5" %%a in ('netstat -ano ^| findstr /c:":%PORT% " ^| findstr /i "LISTENING"') do (
  if not defined FOUND set "FOUND=1"
  echo 正在结束占用 %PORT% 端口的进程 PID=%%a ...
  taskkill /f /pid %%a >nul 2>&1
  if errorlevel 1 (
    echo   失败：可能需要用管理员身份运行此脚本。
  ) else (
    echo   已结束。
  )
)

echo.
if defined FOUND (
  echo 完成。端口 %PORT% 现在空闲，可以重新启动程序了。
) else (
  echo 没有找到正在运行的程序：端口 %PORT% 当前未被占用。
)
echo.
pause
'''

out = ROOT / "停止后台程序.bat"
# 换行必须是 CRLF：cmd 遇到纯 LF 会逐行错位，把每行前半截当成命令执行，
# 表现是「一堆 ''xx'' 不是内部或外部命令」而且所有分支都静默走不到。
out.write_bytes(BODY.replace("\n", "\r\n").encode("gbk"))
print(f"已生成：{out}（{out.stat().st_size} 字节，GBK）")
for i, line in enumerate(BODY.splitlines(), 1):
    if "findstr" in line:
        print(f"  {i}: {line}")
