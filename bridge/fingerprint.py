"""消息指纹：跨采集端共用的「这是不是同一条消息」判据。

为什么单独拆一个模块
    OCR 路径（`sources/dingtalk_ocr.py`）和安卓网关（`sources/android_gateway.py`）
    都要算指纹，而 `dingtalk_ocr` 依赖 Windows UI Automation、导入很重且只能在
    Windows 上跑。指纹算法一旦两边各写一份，早晚会漂移，而漂移的后果很具体：

        同一个发送者有两种写法 → 算出两个指纹 → 同一条消息被采两次 → 重复转发。

    这个坑本仓库已经踩过一次（OCR 把机器人昵称有时读成「签收跟单专员」、
    有时读成「签收跟单专员 机器人」，两条记录正文 md5 完全相同）。所以实现
    只留一份，放在这里。
"""
from __future__ import annotations

import hashlib
import re

SENDER_SPACE_RE = re.compile(r"\s+")
ROBOT_SUFFIX = "机器人"


def norm_sender(sender: str) -> str:
    """发送者归一化，**只用于指纹与相似度判定**，不改变入库/转发时的展示。

    两处实测过的读法抖动，都会把同一条消息算成两条：
      · 机器人昵称的后缀时有时无 —— 同一帧消息分别读成
        「签收跟单专员」和「签收跟单专员 机器人」，正文 md5 完全相同；
      · 昵称被 OCR 拆成两个文本框，拼起来时中间多一个空格。

    这里统一去掉空白与结尾的「机器人」，让它们对上。刻意**不**去掉
    更靠前的字，避免把「签收跟单专员」和「拦截跟单专员」这类不同机器人
    混成同一个。
    """
    s = SENDER_SPACE_RE.sub("", sender or "")
    return s[:-len(ROBOT_SUFFIX)] if s.endswith(ROBOT_SUFFIX) else s


def fp_of(sender: str, content: str) -> str:
    """发送者 + 内容 → 消息指纹。"""
    return hashlib.md5(
        f"{norm_sender(sender)}|{content}".encode("utf-8")
    ).hexdigest()


def unit_fp(unit: dict) -> str:
    """消息单元指纹。``unit`` 需含 ``sender`` 与 ``content``。

    发送者先过一遍 :func:`norm_sender` —— 否则机器人昵称多读/少读一个
    「机器人」后缀就会算出另一个指纹，同一条消息被当成两条重复采、重复转发。
    """
    return fp_of(unit["sender"], unit["content"])


# --------------------------------------------------------------- 近似内容
#
# 为什么还需要一层「近似」：指纹是**精确**匹配，而同一条钉钉机器人卡片在
# 手机上的渲染形态会变，一变就换指纹、换 uid、去重全失效。
#
# 实测（2026-10-17 拦截跟单日报，同一张卡片的两次投递）：
#
#     形态 A（表格识别成功，横排）      形态 B（表格识别失败，一格一行）
#     ─────────────────────────────    ─────────────────────────────
#     指标                             指标
#     10/13 10/14 10/15 10/16 10/17    跟单任务数
#     跟单任务数                        10/13
#     30 21 23 20 17                   30
#     ...
#
# 两次都真的发进了微信群（deliveries 里 18:07:03 / 18:07:07 各一条）。
# 用户的原话是「我手机往上翻页，会发重复的」—— 上翻会让卡片重绘，两种
# 形态来回切，每次都算「新消息」。
#
# 关键观察：**信息完全一样，只是单元格顺序不同**。所以判据不能是比较
# 序列（顺序一变就不等），要比较「**字面构成的集合**」：把排版切碎，看
# 多字符片段是否一一对应。
#
# 为什么不能简单排序整串字符：那样「12」「34」和「13」「24」会撞成同一个。
# 所以按「分隔符 / 换行」切块，块内保序，块之间不计顺序。
_SEP_SPLIT_RE = re.compile(r"[\s\u3000:：,，、;；·•→|｜]+")
# 一个消息要有这么多字才参与近似判重。太短的消息（「收到」「好的」）
# 本来就会重复出现，按近似去重会把正常的重复发言吃掉。
NEAR_MIN_LEN = 30


def content_pieces(content: str) -> list[str]:
    """把正文切成「不计顺序的字面片段」。

    切块依据是排版分隔符（空白、换行、冒号、竖线、箭头……），块内保持
    原顺序、原字符。这样 ``指标 10/13 …`` 与 ``指标 跟单任务数 10/13 …``
    切出来的片集合完全一致，而换了一条真正的消息时集合就对不上。
    """
    return [p for p in _SEP_SPLIT_RE.split(content or "") if p]


def is_same_message(a: str, b: str) -> bool:
    """两段正文是不是「同一条消息的两种渲染」。

    判据：**切成片段后，两边的片段集合完全相等**（无序比较）。

    为什么是「完全相等」而不是「重合度够高」：实测过，同一张卡片两种形态
    的片段集合是 35 vs 35、交集 35，完全一致；而把日报里的一个数字改掉
    （93.33% → 88.10%）后 F1 还有 0.97。用「≥90% 就算重复」会直接把隔天
    的日报吃掉 —— 那是**永久漏发**，比多发一条严重得多。所以宁可把阈值
    收到最紧：只有「字面片段一模一样、只是排列顺序变了」才判重复。

    短消息一律返回 False：宁可多发一条，也不能吃掉正常发言。
    """
    if len(content_key(a)) < NEAR_MIN_LEN or len(content_key(b)) < NEAR_MIN_LEN:
        return False
    sa, sb = set(content_pieces(a)), set(content_pieces(b))
    return bool(sa) and sa == sb


def content_key(content: str) -> str:
    """把排版差异抹平的「内容骨架」（仅用于日志与短消息的精确判重）。

    只抹空白与分隔标点。刻意不抹数字/文字/大小写 —— 宁可漏掉一次近似
    去重（多发一条），也不能把两条不同的日报判成同一条（永久漏发）。
    """
    return re.sub(r"[\s\u3000｜|:：,，、;；·•]+", "", content or "")
