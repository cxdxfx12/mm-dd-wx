"""日志里的「人话」—— 给每天要盯几百行的运维日志留点温度。

用户 2026-10-27：「能不能把日志的提示搞得诙谐有趣一些，像你在思考时的那些
有趣的语句」。三条规矩，改的时候照着来：

  ① **只加在 INFO 上**。WARNING / ERROR 一个字都不许贫 —— 告警是拿来一眼
     看懂然后动手的，不是拿来逗乐的。
  ② **事实永远在最前面**（「已投递 → X」「发现附件「Y」」）。俏皮话只做尾巴：
     界面的计数器（app/gui.py 的 _RE_SENT 等）和 tools/ 里的 grep 都靠前缀。
  ③ **同类事件多备几条随机挑**。天天看同一句「已投递」照样会烦，轮着来才有
     意思；随机是在 import 时就播种的，同一进程里每类会换着出现。

尾巴里刻意带前导分隔符（「，」「（」），调用点直接拼在句尾即可，
读起来像话：`已投递 → 申通五星业务员培训群（微信：收到了，老板）`。
"""
from __future__ import annotations

import random

# 每类事件的尾巴池。写的时候注意：句子要**短**（日志面板一行放不下就折行），
# 别说教、别卖萌过头，最好贴着「搬快递」这个隐喻 —— 这程序本质就是个搬运工。
_TAILS: dict[str, tuple[str, ...]] = {
    # 消息投递成功
    "sent": (
        "（微信：收到，老板）",
        "（已签收，无需本人签字）",
        "（一路小跑送过去了）",
        "（稳稳落地）",
    ),
    # 表格图跟着发出去
    "table_png": (
        "（图也一起搬过去了，挺沉）",
        "（表格已装裱完毕并送达）",
    ),
    # 发现附件、让手机去下载
    "attach_order": (
        "（让手机去搬砖了）",
        "（已派单，骑手是那台安卓机）",
        "（手机：收到，这就去下载）",
    ),
    # 建基线 / 重建基线
    "baseline": (
        "（从现在起只认新来的）",
        "（先照着这屏画个押）",
        "（历史归历史，新账新算）",
    ),
    # 往上翻页补全
    "fill": (
        "（翻了半天，值了）",
        "（又捞回来几条）",
        "（翻页没白费）",
    ),
    # 长消息先攒着
    "pending": (
        "（好饭不怕晚）",
        "（攒齐了再端上桌）",
        "（不着急，等它长完）",
    ),
    # 手机上报帧计数
    "frames": (
        "（心跳稳如老狗）",
        "（手机还在岗）",
        "（一切正常，继续摸鱼）",
    ),
    # 切到微信目标会话
    "chat_open": (
        "（直接进去，不翻通讯录）",
        "（目标明确，一步到位）",
    ),
    # 新增消息
    "new_msgs": (
        "（已转交攒齐层）",
        "（新鲜的，刚出炉）",
        "（收到了，正在打包）",
    ),
    # 基线打捞
    "sweep": (
        "（差点被基线吞了，捞回来了）",
        "（从历史的夹缝里抠出来的）",
    ),
}


def tail(kind: str) -> str:
    """取一条随机尾巴（含前导分隔符）；没有这类事件就返回空串。

    空串而不是抛异常：日志这东西，宁可少一句俏皮话，也不能因为文案表漏了
    一个 key 把主流程炸掉。
    """
    pool = _TAILS.get(kind)
    if not pool:
        return ""
    return random.choice(pool)
